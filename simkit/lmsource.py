"""A private Claude Code config folder for a run whose Living Memory comes from a chosen source checkout.

Claude Code reads the user-level hooks (settings.json) and instructions (CLAUDE.md) from its config folder, so a run
started with `--lm-src PATH` gets runs/<run>/claude-home/ holding only:
  settings.json  the hooks that checkout's integrations/setup.py would install (they run that checkout's hook code),
  CLAUDE.md      that checkout's managed instruction block, exactly core.instructions.instruction_block('claude'),
  .credentials.json, .claude.json  a copy of the login and a minimal state file.
Children get CLAUDE_CONFIG_DIR (Claude Code's folder) and CLAUDE_HOME (Living Memory's SessionStart reads the block
from there to choose the short or the full protocol), so the real ~/.claude is never read or written."""
import json
import shutil
import subprocess
from pathlib import Path

from .common import clean_env, config, write_json

_PROBE = ("import json, sys; sys.path.insert(0, sys.argv[1]); "
          "from integrations import setup; from core.instructions import instruction_block; "
          "print(json.dumps({'hooks': setup.hooks('claude'), 'block': instruction_block('claude')}))")


def read_checkout(src, python=None):
    """{'hooks': ..., 'block': ...} generated by the checkout's own code (run in a child so its modules never mix with ours)."""
    src = Path(src).resolve()
    if not (src / 'living_memory.py').exists():
        raise SystemExit(f'--lm-src {src}: no living_memory.py there')
    r = subprocess.run([python or config()['python'], '-c', _PROBE, str(src)], capture_output=True, text=True,
                       encoding='utf-8', env=clean_env(), timeout=60)
    if r.returncode:
        raise SystemExit(f'--lm-src {src}: cannot read its hooks and instruction block: {r.stderr[-600:]}')
    return json.loads(r.stdout.strip().splitlines()[-1])


def prepare(run_dir, src, real_claude=None):
    """Build runs/<run>/claude-home from the checkout. Returns the folder."""
    home = Path(run_dir) / 'claude-home'
    home.mkdir(parents=True, exist_ok=True)
    found = read_checkout(src)
    write_json(home / 'settings.json', {'hooks': found['hooks']})
    (home / 'CLAUDE.md').write_text(found['block'] + '\n', encoding='utf-8', newline='\n')
    write_json(home / '.claude.json', {'hasCompletedOnboarding': True})
    real = Path(real_claude) if real_claude else Path.home() / '.claude'
    if (real / '.credentials.json').exists():
        shutil.copyfile(real / '.credentials.json', home / '.credentials.json')   # read-only use of the real login
    return home


def home_of(run):
    """The run's private Claude Code config folder (lm_src runs), else None: the user's real ~/.claude is used."""
    return Path(run.dir) / 'claude-home' if run.options.get('lm_src') else None


def env(home):
    return {'CLAUDE_CONFIG_DIR': str(home), 'CLAUDE_HOME': str(home)}
